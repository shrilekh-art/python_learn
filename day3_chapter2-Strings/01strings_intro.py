# ------------------- STRING OPERATIONS NOTES -------------------
# Categories of Python string functions:
#
# 1. Types:
#    - type()        → Built-in function
#    - str()         → Built-in function (constructor)
#
# 2. Math:
#    - len()         → Built-in function
#    - count()       → String method
#
# 3. Transformations:
#    - replace()     → String method
#    - 'H' + 'i'     → Operator (concatenation)
#    - f"{var}"      → Operator (f-string formatting)
#    - split()       → String method
#    - 'ha' * 2      → Operator (repetition)
#    - 'cat'[0]      → Operator (indexing)
#    - 'cat'[1:3]    → Operator (slicing)
#
# 4. Cleaning:
#    - lstrip()      → String method
#    - rstrip()      → String method
#    - strip()       → String method
#    - lower()       → String method
#    - upper()       → String method
#
# 5. Search:
#    - startswith()  → String method
#    - endswith()    → String method
#    - find()        → String method
#    - 'a' in 'cat'  → Operator (membership)
#
# 6. Validation:
#    - isalpha()     → String method
#    - isnumeric()   → String method
#
# Quick Recap:
# - Built-in functions: type(), str(), len()
# - String methods: count(), replace(), split(), strip(), lower(), upper(),
#   startswith(), endswith(), find(), isalpha(), isnumeric()
# - Operators: +, *, indexing [ ], slicing [:], in, f-strings
