# IF Statement Flow:

# Start
# ↓
# Condition (Boolean Expression)
#   → Evaluates to True or False

# If True:
#   → Do Something (execute block A)

# If False:
#   → Do Nothing (skip block)

# End

# Example 1: Check if a number is positive      

num = 5
if num > 0:
    print("The number is positive.")    