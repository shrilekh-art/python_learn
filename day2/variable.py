print("My name is Baraa")
print("Baraa is learning Python")
print("Baraa wants to become Python expert")

name = "Maria"
print("My name is", name)
print(name, "is learning Python")
print(name, "wants to become Python expert")  

name = "Baraa"
print("My name is", name)
print(name, "is learning Python")
print(name, "wants to become Python expert")  


#python executes line by line and the value of name is updated to "Baraa" in the memory. so if we print name after the update, it will print "Baraa" instead of "Maria". this is because the variable name is a reference to the value stored in memory and when we update the variable, it points to the new value in memory.

