# variable is a named storage location in memory that holds a value that can be changed during program execution.
# In python, we can create a variable by simply assigning a value to it using the assignment operator (=). The variable name should follow the rules of variable naming in python, which are:
# 1. Variable names can only contain letters, numbers, and underscores (_).     
# 2. Variable names cannot start with a number.
# 3. Variable names cannot be a reserved keyword in python.
# Example of creating variables in python
name = "John Doe" # string variable 
age = 30 # integer variable
height = 5.9 # float variable
is_student = True # boolean variable
